	ld a,(hl)			;0726
	out (098h),a		;0727
	inc h			;0729
	ld a,(hl)			;072a
	out (098h),a		;072b
	inc h			;072d
	ld a,(hl)			;072e
	out (098h),a		;072f
	inc h			;0731
	ld a,(hl)			;0732
	out (098h),a		;0733
	inc h			;0735
	ld a,(hl)			;0736
	out (098h),a		;0737
	inc h			;0739
	ld a,(hl)			;073a
	out (098h),a		;073b
	inc h			;073d
	ld a,(hl)			;073e   ; La octava, la unica sin `inc h` detras
