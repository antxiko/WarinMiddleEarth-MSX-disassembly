	pop bc			;0744
	pop de			;0745
	pop hl			;0746
	inc h			;0747   ; Siguiente fila de la VRAM: +0x100
	call SIGUIENTE_FILA_ZX		;0748   ; Y la de la pantalla del Spectrum, que no va seguida
